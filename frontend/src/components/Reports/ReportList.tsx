import React, { useState, useEffect, useCallback } from 'react';
import { UserRole } from '../../types';
import type { Report, ReportForm, User } from '../../types';
import { Card } from '../ui/Card';
import { CardHeader } from '../ui/CardHeader';
import { Table, type TableColumn } from '../ui/Table';
import { useCrudForm } from '../../hooks/useCrudForm';

interface ReportListProps {
  projectId?: number;
  user: User;
  token: string;
}

export function ReportList({ projectId, user, token }: ReportListProps): React.ReactElement {
  const [reports, setReports] = useState<Report[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  const listUrl = projectId ? `/api/reports/project/${projectId}` : '/api/reports';

  const fetchReports = useCallback(async (): Promise<void> => {
    setLoading(true);
    setError(null);
    try {
      const res = await fetch(listUrl, {
        headers: { Authorization: `Bearer ${token}` },
      });
      if (!res.ok) throw new Error('Failed to fetch reports');
      const data = await res.json();
      setReports(Array.isArray(data) ? data : data.data ?? []);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Failed to fetch reports');
    } finally {
      setLoading(false);
    }
  }, [listUrl, token]);

  useEffect(() => {
    fetchReports();
  }, [fetchReports]);

  const { showForm, setShowForm, form, handleChange, handleSubmit, handleDelete, resetForm } =
    useCrudForm<ReportForm>({
      initialForm: { ValidationID: '', ProjectID: '', GeneratedBy: '' },
      listUrl: '/api/reports',
      token,
    });

  const handleFormSubmit = useCallback(async (e: React.FormEvent): Promise<void> => {
    await handleSubmit(e);
    await fetchReports();
  }, [handleSubmit, fetchReports]);

  const handleFormDelete = useCallback(async (id: number): Promise<void> => {
    await handleDelete(id);
    await fetchReports();
  }, [handleDelete, fetchReports]);

  const canCreate = user.role === UserRole.ADMIN || user.role === UserRole.FINANCE;
  const canDelete = user.role === UserRole.ADMIN || user.role === UserRole.SUPERVISOR;

  const columns: TableColumn<Report>[] = [
    {
      key: 'project',
      title: 'Project',
      render: (_: unknown, record: Report) => record.Project?.Name ?? String(record.ProjectID),
    },
    {
      key: 'validation',
      title: 'Validation',
      render: (_: unknown, record: Report) => record.Validation?.Status ?? String(record.ValidationID),
    },
    {
      key: 'generatedBy',
      title: 'Generated By',
      dataIndex: 'GeneratedBy',
    },
    {
      key: 'timestamp',
      title: 'Date',
      render: (_: unknown, record: Report) => record.Timestamp?.slice(0, 10) ?? '',
    },
    ...(canDelete
      ? [
          {
            key: 'actions',
            title: 'Actions',
            render: (_: unknown, record: Report) => (
              <button onClick={() => handleFormDelete(record.ReportID)} className="btn btn--danger">Delete</button>
            ),
          },
        ]
      : []),
  ];

  return (
    <Card variant="outlined">
      <CardHeader
        title="Reports"
        actions={
          <button onClick={() => setShowForm(true)} disabled={!canCreate} className="btn btn--primary">
            + New Report
          </button>
        }
      />
      {error && <p className="error" role="alert" aria-live="polite">{error}</p>}
      {showForm && (
        <form onSubmit={handleFormSubmit} className="report-form">
          <label htmlFor="r-validation-id">Validation ID</label>
          <input id="r-validation-id" name="ValidationID" type="number" placeholder="Validation ID" value={form.ValidationID} onChange={handleChange} required className="input" />
          <label htmlFor="r-project-id">Project ID</label>
          <input id="r-project-id" name="ProjectID" type="number" placeholder="Project ID" value={form.ProjectID} onChange={handleChange} required className="input" />
          <label htmlFor="r-generated-by">Generated By</label>
          <input id="r-generated-by" name="GeneratedBy" placeholder="Generated By" value={form.GeneratedBy} onChange={handleChange} required className="input" />
          <button type="submit" className="btn btn--primary">Create</button>
          <button type="button" onClick={resetForm} className="btn btn--secondary">Cancel</button>
        </form>
      )}
      <Table
        dataSource={reports}
        columns={columns}
        loading={loading}
        rowKey={(r) => r.ReportID}
        emptyState={
          <>
            <div className="enhanced-table__empty-icon">📋</div>
            <div className="enhanced-table__empty-text">No reports yet</div>
          </>
        }
        caption="Billing and project reports"
      />
    </Card>
  );
}
