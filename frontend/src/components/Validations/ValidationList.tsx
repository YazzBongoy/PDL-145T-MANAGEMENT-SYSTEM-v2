import React, { useState, useEffect, useCallback } from 'react';
import { UserRole, ValidationStatus } from '../../types';
import type { Validation, ValidationForm, User } from '../../types';
import { Card } from '../ui/Card';
import { CardHeader } from '../ui/CardHeader';
import { Table, type TableColumn } from '../ui/Table';
import { Badge } from '../ui/Badge';
import { useCrudForm } from '../../hooks/useCrudForm';

interface ValidationListProps {
  taskId?: number;
  user: User;
  token: string;
}

const STATUS_VARIANT: Record<string, string> = {
  Pending: 'warning',
  Approved: 'success',
  Rejected: 'error',
};

export function ValidationList({ taskId, user, token }: ValidationListProps): React.ReactElement {
  const [validations, setValidations] = useState<Validation[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  const listUrl = taskId ? `/api/validations/task/${taskId}` : '/api/validations';

  const fetchValidations = useCallback(async (): Promise<void> => {
    setLoading(true);
    setError(null);
    try {
      const res = await fetch(listUrl, {
        headers: { Authorization: `Bearer ${token}` },
      });
      if (!res.ok) throw new Error('Failed to fetch validations');
      const data = await res.json();
      setValidations(Array.isArray(data) ? data : data.data ?? []);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Failed to fetch validations');
    } finally {
      setLoading(false);
    }
  }, [listUrl, token]);

  useEffect(() => {
    fetchValidations();
  }, [fetchValidations]);

  const { showForm, setShowForm, form, editId, handleChange, handleSubmit, handleEdit, handleDelete, resetForm } =
    useCrudForm<ValidationForm>({
      initialForm: { TaskID: '', SiteID: '', Notes: '', GeneratedBy: '' },
      listUrl: '/api/validations',
      token,
    });

  const handleFormSubmit = useCallback(async (e: React.FormEvent): Promise<void> => {
    await handleSubmit(e);
    await fetchValidations();
  }, [handleSubmit, fetchValidations]);

  const handleFormEdit = useCallback((v: Validation): void => {
    handleEdit(v as unknown as Record<string, unknown>, (item) => ({
      TaskID: String(item.TaskID ?? ''),
      SiteID: (item.SiteID as string) || '',
      Notes: (item.Notes as string) || '',
      GeneratedBy: (item.GeneratedBy as string) || '',
    }));
  }, [handleEdit]);

  const handleFormDelete = useCallback(async (id: number): Promise<void> => {
    await handleDelete(id);
    await fetchValidations();
  }, [handleDelete, fetchValidations]);

  const handleApprove = useCallback(async (id: number): Promise<void> => {
    try {
      const res = await fetch(`/api/validations/${id}/approve`, {
        method: 'POST',
        headers: { Authorization: `Bearer ${token}` },
      });
      if (!res.ok) throw new Error('Failed to approve');
      await fetchValidations();
    } catch (err) {
      alert(err instanceof Error ? err.message : 'Failed to approve');
    }
  }, [token, fetchValidations]);

  const handleReject = useCallback(async (id: number): Promise<void> => {
    try {
      const res = await fetch(`/api/validations/${id}/reject`, {
        method: 'POST',
        headers: { Authorization: `Bearer ${token}` },
      });
      if (!res.ok) throw new Error('Failed to reject');
      await fetchValidations();
    } catch (err) {
      alert(err instanceof Error ? err.message : 'Failed to reject');
    }
  }, [token, fetchValidations]);

  const canEdit = user.role === UserRole.ADMIN || user.role === UserRole.SUPERVISOR;
  const canApprove = user.role === UserRole.ADMIN || user.role === UserRole.FINANCE;

  const columns: TableColumn<Validation>[] = [
    {
      key: 'status',
      title: 'Status',
      render: (_: unknown, record: Validation) => (
        <Badge variant={STATUS_VARIANT[record.Status] as 'warning' | 'success' | 'error' ?? 'default'}>
          {record.Status}
        </Badge>
      ),
    },
    {
      key: 'site',
      title: 'Site',
      render: (_: unknown, record: Validation) => record.Site?.Name ?? record.SiteID,
    },
    {
      key: 'generatedBy',
      title: 'Generated By',
      dataIndex: 'GeneratedBy',
    },
    {
      key: 'timestamp',
      title: 'Date',
      render: (_: unknown, record: Validation) => record.Timestamp?.slice(0, 10) ?? '',
    },
    {
      key: 'actions',
      title: 'Actions',
      render: (_: unknown, record: Validation) => (
        <>
          {canApprove && record.Status === ValidationStatus.PENDING && (
            <>
              <button onClick={() => handleApprove(record.ValidationID)} className="btn btn--primary">Approve</button>
              <button onClick={() => handleReject(record.ValidationID)} className="btn btn--danger">Reject</button>
            </>
          )}
          {canEdit && (
            <>
              <button onClick={() => handleFormEdit(record)} className="btn btn--secondary">Edit</button>
              <button onClick={() => handleFormDelete(record.ValidationID)} className="btn btn--danger">Delete</button>
            </>
          )}
        </>
      ),
    },
  ];

  return (
    <Card variant="outlined">
      <CardHeader
        title="Validations"
        actions={
          <button onClick={() => setShowForm(true)} disabled={!canEdit} className="btn btn--primary">
            + New Validation
          </button>
        }
      />
      {error && <p className="error" role="alert" aria-live="polite">{error}</p>}
      {showForm && (
        <form onSubmit={handleFormSubmit} className="validation-form">
          {!editId && (
            <>
              <label htmlFor="v-task-id">Task ID</label>
              <input id="v-task-id" name="TaskID" type="number" placeholder="Task ID" value={form.TaskID} onChange={handleChange} required className="input" />
            </>
          )}
          <label htmlFor="v-site-id">Site ID</label>
          <input id="v-site-id" name="SiteID" placeholder="Site ID" value={form.SiteID} onChange={handleChange} required className="input" />
          <label htmlFor="v-notes">Notes</label>
          <input id="v-notes" name="Notes" placeholder="Notes" value={form.Notes} onChange={handleChange} className="input" />
          <label htmlFor="v-generated-by">Generated By</label>
          <input id="v-generated-by" name="GeneratedBy" placeholder="Generated By" value={form.GeneratedBy} onChange={handleChange} required className="input" />
          <button type="submit" className="btn btn--primary">{editId ? 'Update' : 'Create'}</button>
          <button type="button" onClick={resetForm} className="btn btn--secondary">Cancel</button>
        </form>
      )}
      <Table
        dataSource={validations}
        columns={columns}
        loading={loading}
        rowKey={(r) => r.ValidationID}
        emptyState={
          <>
            <div className="enhanced-table__empty-icon">✅</div>
            <div className="enhanced-table__empty-text">No validations yet</div>
          </>
        }
        caption="Construction site validations"
      />
    </Card>
  );
}
